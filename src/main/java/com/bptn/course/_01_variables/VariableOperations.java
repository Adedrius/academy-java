package com.bptn.course._01_variables;

public class VariableOperations {
	
	public static void main(String[] args) {
		// Declaring two integer variables and assigning them values.
		int num1 = 6;
		int num2 = 2;
		
		// Performing arithmetic operations (addition, subtraction, multiplication, and division) using the variables and storing the results in new variables.
		int sum = num1 + num2;
		int diff = num1 - num2;
		int product = num1 * num2;
		int quotient = num1 / num2;
		
		// Printing the original variables and the results of the arithmetic operations.
		System.out.println(num1);	
		System.out.println(num2);
		System.out.println();
		System.out.println(sum);
		System.out.println(diff);
		System.out.println(product);
		System.out.println(quotient);
		
		// Reassigning new values to the original integer variables and printing them to show the changes.
		num1 = 20;
		num2 = 4;
		
		System.out.println();
		System.out.println(num1);	
		System.out.println(num2);
		
		
		// Declaring a character variable and a string variable and printing them.
		char firstLetter = 'a';
		String alphabet = "a is the first letter of the alphabet.";
		
		System.out.println();
		System.out.println(firstLetter);	
		System.out.println(alphabet);
		
	}
}

